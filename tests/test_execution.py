import os
import shutil
from pathlib import Path

import pytest
from testbook import testbook
from conftest import NOTEBOOKS, REPO_ROOT

# Timeouts are per notebook cell, in seconds
CATEGORY_TIMEOUTS = {
    "data": 300,
    "generation": 1200,
    "processing": 2400,
    "reconstruction": 180,
    "visualization": 180,
}

# Notebooks requiring high RAM, large disk space, or long run times, tests pass on dtu hpc
HEAVY_NOTEBOOKS = {
    "generation/Large_data_generation.ipynb": "Generates a 2000^3 synthetic volume (~15 min, several GB of disk).",
    "processing/Larger_than_memory_processing.ipynb": "Generates and processes a ~36 GB synthetic volume (~15 min).",
    "processing/Dask_OME-zarr_pipeline-OpticalNerve.ipynb": "Reads OpticalNerve.zarr from the DTU 3D Imaging Center file share.",
    "processing/Dask_OME-zarr_pipeline.ipynb": "Needs vol_2000.zarr, which Large_data_generation creates (~15 min).",
    "processing/Reconstructed_data_insights.ipynb": "Reads a .txm file from the DTU 3D Imaging Center file share.",
}

# Notebooks that can never run in automated execution, regardless of flags
ALWAYS_SKIPPED_NOTEBOOKS = {
    "reconstruction/padding.ipynb": "Needs the Conda-only CIL package (cil) and CT data from a DTU project folder that is not generally accessible.",
    "reconstruction/ct_subsampling.ipynb": "Requires the Conda-only C++ package ccpi-regulariser, which cannot be installed from PyPI.",
    "visualization/Volume_explorer.ipynb": "Needs the interactive Node.js Volume Explorer app; qim3d prompts via input() when it is missing, which fails headless.",
}

# Large_data_generation writes vol_2000.zarr. The notebooks below read it, so it is generated once per
# test session and linked into their working directory.
VOL_2000_PRODUCER = "generation/Large_data_generation.ipynb"
VOL_2000_CONSUMERS = {"processing/Dask_OME-zarr_pipeline.ipynb"}


def get_timeout(nb_path: Path) -> int:
    return CATEGORY_TIMEOUTS.get(nb_path.parent.name, 180)


def run_notebook(nb_path: Path, cwd: Path) -> None:
    """Execute a notebook with `cwd` as its working directory. Raises if any cell fails."""
    previous = Path.cwd()
    os.chdir(cwd)
    try:
        with testbook(str(nb_path.resolve()), execute=True, timeout=get_timeout(nb_path)):
            pass
    finally:
        os.chdir(previous)


@pytest.fixture(scope="session")
def shared_vol_2000(tmp_path_factory):
    """Holds the vol_2000.zarr generated by Large_data_generation, shared by all tests that need it."""
    state = {"work_dir": tmp_path_factory.mktemp("shared_vol_2000"), "started": False, "done": False}
    yield state
    shutil.rmtree(state["work_dir"], ignore_errors=True)


def ensure_vol_2000(state) -> Path:
    """Run Large_data_generation once and return the path to its vol_2000.zarr."""
    if not state["started"]:
        state["started"] = True
        run_notebook(REPO_ROOT / VOL_2000_PRODUCER, state["work_dir"])
        state["done"] = True
    if not state["done"]:
        pytest.fail("Large_data_generation failed earlier, so vol_2000.zarr is not available")
    return state["work_dir"] / "vol_2000.zarr"


@pytest.mark.execution
@pytest.mark.parametrize(
    "nb_path", NOTEBOOKS, ids=lambda p: f"{p.parent.name}/{p.stem}"
)
def test_notebook_runs(nb_path, tmp_work_dir, request, shared_vol_2000):
    rel_path = nb_path.relative_to(REPO_ROOT).as_posix()
    if rel_path in ALWAYS_SKIPPED_NOTEBOOKS:
        pytest.skip(f"Always skipped: {ALWAYS_SKIPPED_NOTEBOOKS[rel_path]}")
    if rel_path in HEAVY_NOTEBOOKS:
        if not request.config.getoption("--run-heavy"):
            pytest.skip(
                f"Skipping heavy notebook (use --run-heavy to run): {HEAVY_NOTEBOOKS[rel_path]}"
            )

    if rel_path == VOL_2000_PRODUCER:
        # Running it also produces the volume the consumers need, so this is the only execution
        ensure_vol_2000(shared_vol_2000)
        return
    if rel_path in VOL_2000_CONSUMERS:
        (tmp_work_dir / "vol_2000.zarr").symlink_to(
            ensure_vol_2000(shared_vol_2000), target_is_directory=True
        )

    run_notebook(nb_path, tmp_work_dir)
